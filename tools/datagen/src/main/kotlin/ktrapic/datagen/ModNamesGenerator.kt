package ktrapic.datagen

/**
 * Generates the in-game plugin's list of the runtime API's generated names, which its editor
 * highlights: the types the generated sources declare (prefabs, their entry points and families,
 * slot kinds), the enums and their values, and the logic types devices and slots have.
 */
object ModNamesGenerator {
  /** Where the file goes, relative to the workspace root. */
  const val PATH = "mod/src/RuntimeNames.g.cs"

  private val DECLARATION =
      Regex("""^\s*(?:abstract |sealed |open |data |enum )*(?:class|object|interface) (\w+)""")

  /** The C# source for [generated], the runtime's generated sources, made from [enums]. */
  fun generate(generated: Map<String, String>, enums: LogicEnums): String {
    val enumNames = enums.enums.keys.toSortedSet()
    val logicTypes =
        (enums.enums["LogicType"].orEmpty().keys + enums.enums["LogicSlotType"].orEmpty().keys)
            .filter { it != "None" }
            .toSortedSet()
    val types =
        generated.values
            .flatMap { it.lineSequence() }
            .mapNotNull { DECLARATION.find(it)?.groupValues?.get(1) }
            .filter { it !in enumNames }
            .toSortedSet()
    // An operand enum's values are the logic types themselves, which are highlighted as such.
    val enumValues =
        enums.enums.values.flatMap { it.keys }.filter { it !in logicTypes && it != "None" }
    return buildString {
      append(
          "// Generated by //tools/datagen from runtime/data. Do not edit; regenerate instead.\n"
      )
      append("\n")
      append("namespace KTrapIC\n")
      append("{\n")
      append(
          "    /// <summary>The runtime API's generated names, for the editor to highlight.</summary>\n"
      )
      append("    internal static class RuntimeNames\n")
      append("    {\n")
      list("Types", types)
      append("\n")
      list("Enums", enumNames)
      append("\n")
      list("EnumValues", enumValues.toSortedSet())
      append("\n")
      list("LogicTypes", logicTypes)
      append("    }\n")
      append("}\n")
    }
  }

  private fun StringBuilder.list(name: String, names: Set<String>) {
    append("        public static readonly string[] $name =\n")
    append("        {\n")
    for (n in names) append("            \"$n\",\n")
    append("        };\n")
  }
}
