package ktrapic.datagen

/**
 * Generates the in-game plugin's list of the SDK's generated names, which its editor highlights:
 * the types the generated sources declare (prefabs, their entry points and families, slot kinds),
 * the enums and their values, and the logic types devices and slots have.
 */
object ModNamesGenerator {
  /** Where the file goes, relative to the workspace root. */
  const val PATH = "mod/src/SdkNames.g.cs"

  /** The enums that name a logic type, whose values (but `None`) are the logic types. */
  private val OPERAND_ENUMS = listOf("LogicType", "LogicSlotType")

  private val DECLARATION =
      Regex("""^\s*(?:abstract |sealed |open |data |enum )*(?:class|object|interface) (\w+)""")

  /** The C# source for [generated], the SDK's generated sources, made from [enums]. */
  fun generate(generated: Map<String, String>, gameEnums: LogicEnums): String {
    // The views' Substance is an enum of the SDK's own, keyed by name rather than a number.
    val substances = LogicViews.substances(gameEnums.enums["LogicType"].orEmpty().keys)
    val enums =
        if (substances.isEmpty()) gameEnums
        else
            gameEnums.copy(
                enums =
                    gameEnums.enums +
                        ("Substance" to substances.withIndex().associate { it.value to it.index })
            )
    val enumNames = enums.enums.keys.toSortedSet()
    val logicTypes =
        OPERAND_ENUMS.flatMap { enums.enums[it].orEmpty().keys }
            .filter { it != "None" }
            .toSortedSet()
    val types =
        generated.values
            .flatMap { it.lineSequence() }
            .mapNotNull { DECLARATION.find(it)?.groupValues?.get(1) }
            .filter { it !in enumNames }
            .toSortedSet()
    return buildString {
      append("// Generated by //tools/datagen from sdk/data. Do not edit; regenerate instead.\n")
      append("\n")
      append("using System.Collections.Generic;\n")
      append("\n")
      append("namespace KTrapIC\n")
      append("{\n")
      append("    /// <summary>The SDK's generated names, for the editor to highlight.</summary>\n")
      append("    internal static class SdkNames\n")
      append("    {\n")
      list("Types", types)
      append("\n")
      append("        /// <summary>Each enum's values, by the enum.</summary>\n")
      append(
          "        public static readonly Dictionary<string, string[]> Enums =" +
              " new Dictionary<string, string[]>\n"
      )
      append("        {\n")
      for (name in enumNames) {
        append("            [\"$name\"] = new[]\n")
        append("            {\n")
        for (value in enums.enums.getValue(name).keys.toSortedSet()) {
          append("                \"$value\",\n")
        }
        append("            },\n")
      }
      append("        };\n")
      append("\n")
      append(
          "        /// <summary>The enums whose values are logic types: an instruction's operand.</summary>\n"
      )
      list("OperandEnums", OPERAND_ENUMS.filter { it in enumNames }.toSortedSet())
      append("\n")
      list("LogicTypes", logicTypes)
      append("    }\n")
      append("}\n")
    }
  }

  private fun StringBuilder.list(name: String, names: Set<String>) {
    append("        public static readonly string[] $name =\n")
    append("        {\n")
    for (n in names) append("            \"$n\",\n")
    append("        };\n")
  }
}
