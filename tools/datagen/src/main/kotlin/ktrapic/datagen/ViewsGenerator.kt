package ktrapic.datagen

/**
 * Generates `GeneratedViews.kt`: the [LogicViews] a device's logic types are grouped into, and the
 * `Substance` enum that keys the ratios. A member is `var` only where some prefab lets a program
 * write one of its logic types; which ones a given device has is checked by the compiler against
 * the device's `@LogicTypes`.
 */
object ViewsGenerator {
  const val FILE = "GeneratedViews.kt"

  fun generate(logicTypes: Collection<String>, typing: Typing, prefabs: Prefabs): String {
    val booleans = typing.booleanLogicTypes.toSet()
    val written = prefabs.prefabs.flatMap { p -> p.logic.filterValues { it.write }.keys }.toSet()
    val substances = LogicViews.substances(logicTypes)
    fun type(logicType: String) = if (logicType in booleans) "Boolean" else "Double"

    return buildString {
      append(
          "// Generated by //tools/datagen from runtime/data. Do not edit; regenerate instead.\n"
      )
      append("\n")
      append("package ktrapic\n")
      append("\n")
      append("/** The substances whose ratios a device reports, the keys of [Ratios]. */\n")
      append("enum class Substance {\n")
      for (substance in substances) append("  $substance,\n")
      append("}\n")
      append("\n")
      append("/** A device's ports, each with its own pressure, temperature and contents. */\n")
      append("class Ports internal constructor() {\n")
      for ((i, port) in LogicViews.PORTS.withIndex()) {
        if (i > 0) append("\n")
        append("  val $port: Port\n")
        append("    get() = intrinsic()\n")
      }
      append("}\n")
      append("\n")
      append("/** One of a device's [Ports]. */\n")
      append("class Port internal constructor() {\n")
      for (member in LogicViews.PORT_MEMBERS) {
        val variants = LogicViews.PORTS.map { member + it }.filter { it in logicTypes }
        if (variants.isEmpty()) continue
        val keyword = if (variants.any { it in written }) "var" else "val"
        append("  $keyword $member: ${type(variants.first())}\n")
        append("    get() = intrinsic()\n")
        if (keyword == "var") append("    set(value) = intrinsic()\n")
        append("\n")
      }
      append("  /** The port's contents, as the ratio of each [Substance]. */\n")
      append("  val Ratios: Ratios\n")
      append("    get() = intrinsic()\n")
      append("}\n")
      append("\n")
      append("/**\n")
      append(
          " * The ratio of each [Substance] in a device or one of its ports: `sensor.Ratios[Substance.Oxygen]`.\n"
      )
      append(" * The key must be a constant, and one the device reports.\n")
      append(" */\n")
      append("class Ratios internal constructor() {\n")
      append("  operator fun get(substance: Substance): Double = intrinsic()\n")
      append("\n")
      append("  /** The substances the device reports, a set known when compiled. */\n")
      append("  val keys: Set<Substance>\n")
      append("    get() = intrinsic()\n")
      append("\n")
      append(
          "  /** Each substance the device reports with its ratio: `for ((gas, ratio) in ratios)`. */\n"
      )
      append("  operator fun iterator(): Iterator<Map.Entry<Substance, Double>> = intrinsic()\n")
      append("}\n")
      append("\n")
      append("/** A vector a device reports, by axis. */\n")
      append("class Vector internal constructor() {\n")
      for ((i, axis) in listOf("X", "Y", "Z").withIndex()) {
        if (i > 0) append("\n")
        append("  val $axis: Double\n")
        append("    get() = intrinsic()\n")
      }
      append("}\n")
      append("\n")
      append("/** A vector a device reports and a program can set, by axis. */\n")
      append("class MutableVector internal constructor() {\n")
      for ((i, axis) in listOf("X", "Y", "Z").withIndex()) {
        if (i > 0) append("\n")
        append("  var $axis: Double\n")
        append("    get() = intrinsic()\n")
        append("    set(value) = intrinsic()\n")
      }
      append("}\n")
      append("\n")
      append("/** What a device imports or exports. */\n")
      append("class Transfer internal constructor() {\n")
      for ((i, member) in LogicViews.TRANSFER_MEMBERS.withIndex()) {
        if (i > 0) append("\n")
        append("  val $member: ${type("Import$member")}\n")
        append("    get() = intrinsic()\n")
      }
      append("}\n")
    }
  }

  /**
   * The type of the device-level view [view] on a device that writes [written] of its logic types:
   * a vector is a [MutableVector] if any of its axes can be written.
   */
  fun viewType(view: String, written: Collection<String>): String =
      when (view) {
        "Ports" -> "Ports"
        "Ratios" -> "Ratios"
        in LogicViews.VECTORS -> if (written.isEmpty()) "Vector" else "MutableVector"
        in LogicViews.TRANSFERS -> "Transfer"
        else -> error("not a view: $view")
      }
}
