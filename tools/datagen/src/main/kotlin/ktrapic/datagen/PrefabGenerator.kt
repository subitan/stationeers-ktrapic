package ktrapic.datagen

/**
 * Generates the typed device API: per prefab, a device class whose companion object is the prefab
 * as a value, and a plural entry point with `at(pin)`, `all` and `named(name)`, whose batches
 * (`Batch` in `Batches.kt`) hold the prefab's typed devices.
 *
 * A prefab in one of the [Grouping.families] is generated inside it: `Battery.Small` is the device
 * class, nested in the `Battery` interface that holds the logic types every member can read, and
 * `Batteries.Small` its entry point. Every other prefab is generated flat, named after its prefab
 * without a leading `Structure` or `Item` (`StructureGrowLight` is `GrowLight` and `GrowLights`),
 * or with its whole name where that would clash.
 */
object PrefabGenerator {
  private const val FILE = "GeneratedPrefabs.kt"
  private val PREFIXES = listOf("Structure", "Item")
  private const val CONSOLE_SLOT_KIND = "Circuitboard"

  /** Names declared elsewhere in the `ktrapic` package, which no prefab may take. */
  private val HAND_WRITTEN =
      setOf(
          "Device",
          "GenericDevice",
          "TypedDevice",
          "Prefab",
          "DeviceBatch",
          "Batch",
          "Mapped",
          "Ic10Script",
          "PrefabName",
          "Slot",
          "Slots",
          "DeviceSlot",
          "SlotBatch",
          "SlotNumber",
          "LogicTypes",
          "Substance",
          "Ports",
          "Port",
          "Ratios",
          "Vector",
          "MutableVector",
          "Transfer",
      )

  fun generate(
      prefabs: Prefabs,
      grouping: Grouping,
      enumNames: Set<String>,
      typing: Typing,
      substances: Set<String> = emptySet(),
  ): Pair<String, String> {
    val byName = prefabs.prefabs.associateBy { it.name }
    val inFamily = mutableMapOf<String, String>()
    for ((family, members) in grouping.families) {
      for ((member, prefab) in members.members) {
        require(prefab in byName) { "family $family member $member: no prefab $prefab" }
        val previous = inFamily.put(prefab, family)
        require(previous == null) { "$prefab is in both $previous and $family" }
      }
    }
    for (prefab in grouping.textDisplays) {
      require(prefab in byName) { "text display $prefab is not a prefab" }
      require(byName.getValue(prefab).logic["Setting"]?.write == true) {
        "text display $prefab has no writable Setting"
      }
    }

    val taken = (HAND_WRITTEN + enumNames).toMutableSet()
    fun claim(name: String, what: String) {
      identifier(name)
      require(taken.add(name)) { "$what: the name $name is already taken" }
    }
    for (kind in prefabs.slotKinds.keys) claim(slotClass(kind), "slot kind $kind")
    for (prefab in prefabs.prefabs) {
      for ((number, slot) in prefab.slots) {
        require(slot.kind in prefabs.slotKinds) {
          "${prefab.name} slot $number: no slot kind ${slot.kind}"
        }
      }
    }
    checkConsoles(prefabs, typing.consoles.toSet())
    val things = checkThings(prefabs, typing)
    // A thing's slots follow the game's rules for things; Common is what any of them can read.
    val thingKinds =
        (prefabs.prefabs
                .filter { it.name in things }
                .flatMap { p -> p.slots.values.map { it.kind } } + "Common")
            .toSortedSet()
    for (kind in thingKinds) claim(thingSlotClass(kind), "slot kind $kind of things")
    for ((family, members) in grouping.families) {
      claim(family, "family $family")
      claim(members.plural, "family $family")
    }
    val flat = prefabs.prefabs.filter { it.name !in inFamily }
    val shortNames = flat.groupingBy { shortName(it.name) }.eachCount()
    val names = flat.associate { prefab ->
      val short = shortName(prefab.name)
      val name =
          if (shortNames.getValue(short) == 1 && short !in taken) short else sanitize(prefab.name)
      prefab.name to name
    }
    for (prefab in flat) {
      val name = names.getValue(prefab.name)
      claim(name, prefab.name)
      claim(plural(name), prefab.name)
    }

    val out = Out(typing, grouping.textDisplays.toSet(), prefabs.slotKinds, things, substances)
    out.line("// Generated by //tools/datagen from runtime/data. Do not edit; regenerate instead.")
    out.line()
    out.line("package ktrapic")
    for (kind in prefabs.slotKinds.keys) out.slotKind(kind)
    for (kind in thingKinds) out.thingSlotKind(kind)
    val common =
        grouping.families.mapValues { (_, members) ->
          out.common(members.members.values.map { byName.getValue(it) })
        }
    for ((family, members) in grouping.families) {
      val memberPrefabs = members.members.mapValues { byName.getValue(it.value) }
      out.family(
          family,
          members.plural,
          memberPrefabs,
          members.extends,
          inherited(family, grouping, common),
      )
    }
    for (prefab in flat) {
      out.line()
      out.deviceClass(names.getValue(prefab.name), prefab, supertypes = "TypedDevice()")
      out.line()
      out.entryPoint(
          "object ${plural(names.getValue(prefab.name))}",
          names.getValue(prefab.name),
          prefab,
      )
    }
    return FILE to out.toString()
  }

  /**
   * The logic types [family] inherits from the families it extends, directly or through them, with
   * their access there. Checks that it extends only other families, without a cycle, and that all
   * of its members can read each logic type it inherits and write each one inherited as a `var`.
   */
  private fun inherited(
      family: String,
      grouping: Grouping,
      common: Map<String, Map<String, Access>>,
  ): Map<String, Access> {
    val ancestors = mutableListOf<String>()
    fun visit(name: String, path: List<String>) {
      for (parent in grouping.families.getValue(name).extends) {
        require(parent in grouping.families) { "family $name extends $parent, which is no family" }
        require(parent != family && parent !in path) {
          "family $family extends itself, through ${(path + parent).joinToString(" -> ")}"
        }
        if (parent !in ancestors) ancestors += parent
        visit(parent, path + parent)
      }
    }
    visit(family, listOf(family))
    val own = common.getValue(family)
    val inherited = mutableMapOf<String, Access>()
    for (ancestor in ancestors) {
      for ((logicType, access) in common.getValue(ancestor)) {
        val mine = own[logicType]
        require(mine != null && (mine.write || !access.write)) {
          "family $family extends $ancestor, but not all of its members can " +
              "${if (access.write) "write" else "read"} $logicType"
        }
        inherited.merge(logicType, access) { a, b ->
          Access(read = true, write = a.write || b.write)
        }
      }
    }
    return inherited
  }

  /**
   * Checks that [consoles] are exactly the prefabs with `Circuitboard` slots, and have only those.
   * The game lets a console write `Mode` on any of its slots; the typed API gives `Mode` to the
   * `Circuitboard` slot kind instead, which matches the game only while that holds.
   */
  private fun checkConsoles(prefabs: Prefabs, consoles: Set<String>) {
    val names = prefabs.prefabs.map { it.name }.toSet()
    for (console in consoles) require(console in names) { "console $console is not a prefab" }
    for (prefab in prefabs.prefabs) {
      val kinds = prefab.slots.values.map { it.kind }.toSet()
      if (prefab.name in consoles) {
        require(kinds == setOf(CONSOLE_SLOT_KIND)) {
          "console ${prefab.name} has slots of kinds $kinds, not only $CONSOLE_SLOT_KIND"
        }
      } else {
        require(CONSOLE_SLOT_KIND !in kinds) {
          "${prefab.name} has a $CONSOLE_SLOT_KIND slot but is not a console"
        }
      }
    }
  }

  /**
   * The prefabs with slots that are things (items, robots, rovers) rather than structures, whose
   * slots follow the game's rules for things. A prefab named `Structure...` is a structure; every
   * other prefab with slots must be in [Typing.slottedThings] or [Typing.slottedStructures], since
   * a name alone doesn't say which.
   */
  private fun checkThings(prefabs: Prefabs, typing: Typing): Set<String> {
    val things = typing.slottedThings.toSet()
    val structures = typing.slottedStructures.toSet()
    val slotted = prefabs.prefabs.filter { it.slots.isNotEmpty() }.map { it.name }.toSet()
    for (name in things + structures) {
      require(name in slotted) {
        "$name is listed as a thing or structure with slots, but has none"
      }
    }
    require((things intersect structures).isEmpty()) {
      "listed as both a thing and a structure: ${things intersect structures}"
    }
    for (name in things) require(!name.startsWith("Structure")) { "$name is named as a structure" }
    for (name in slotted) {
      require(name.startsWith("Structure") || name in things || name in structures) {
        "$name has slots: list it in typing.json as a thing or a structure"
      }
    }
    return things
  }

  private fun shortName(prefab: String): String =
      sanitize(
          PREFIXES.firstOrNull { prefab.startsWith(it) && prefab.length > it.length }
              ?.let { prefab.removePrefix(it) } ?: prefab
      )

  /**
   * A prefab name as an identifier: `TransformerMedium(Reversed)` is `TransformerMedium_Reversed`.
   */
  private fun sanitize(name: String): String =
      name.replace(Regex("[^A-Za-z0-9_]+"), "_").trimEnd('_').let {
        if (it.first().isDigit()) "_$it" else it
      }

  fun plural(name: String): String =
      when {
        name.length > 1 &&
            name.endsWith("y") &&
            name[name.length - 2].lowercaseChar() !in "aeiou" -> name.dropLast(1) + "ies"
        listOf("s", "x", "z", "ch", "sh").any { name.endsWith(it) } -> name + "es"
        else -> name + "s"
      }

  /** The class of a kind of slot: `Battery` slots are `BatterySlot`s. */
  fun slotClass(kind: String) = "${kind}Slot"

  /** The class of a kind of slot on a thing (an item, a robot, a rover): `ItemBatterySlot`. */
  fun thingSlotClass(kind: String) = "Item${kind}Slot"

  /** The device-level views, in the order a device class declares them. */
  private val VIEW_ORDER =
      listOf("Ports", "Ratios") + LogicViews.VECTORS.keys + LogicViews.TRANSFERS

  private val IDENTIFIER = Regex("[A-Za-z_][A-Za-z0-9_]*")

  private fun identifier(name: String) {
    require(IDENTIFIER.matches(name)) { "not a Kotlin identifier: $name" }
  }

  /** Writes ktfmt-formatted Kotlin, one indentation level per nesting. */
  private class Out(
      val typing: Typing,
      val textDisplays: Set<String>,
      val slotKinds: Map<String, List<String>>,
      val things: Set<String>,
      val substances: Set<String>,
  ) {
    val booleans = typing.booleanLogicTypes.toSet()

    private val text = StringBuilder()
    private var indent = 0

    fun line(line: String = "") {
      if (line.isNotEmpty()) repeat(indent) { text.append("  ") }
      text.append(line).append('\n')
    }

    fun block(header: String, body: () -> Unit) {
      line("$header {")
      indent++
      body()
      indent--
      line("}")
    }

    fun type(logicType: String) = if (logicType in booleans) "Boolean" else "Double"

    /**
     * The logic types a property of their own is generated for: all but the hashes every device
     * has, and those in a view ([views]).
     */
    fun logic(prefab: Prefab) =
        prefab.logic.filterKeys {
          it !in setOf("PrefabHash", "NameHash", "ReferenceId") &&
              LogicViews.viewOf(it, substances) == null
        }

    /** A prefab's logic types that are in views, by view, in [LogicViews]'s order. */
    fun views(prefab: Prefab): Map<String, Map<String, Access>> =
        prefab.logic.entries
            .mapNotNull { (logicType, access) ->
              LogicViews.viewOf(logicType, substances)?.let { Triple(it, logicType, access) }
            }
            .groupBy({ it.first }, { it.second to it.third })
            .mapValues { (_, types) -> types.toMap() }
            .toSortedMap(compareBy { VIEW_ORDER.indexOf(it) })

    /**
     * A view property, with the logic types it reaches on this prefab for the compiler to check:
     * `@LogicTypes(read = ..., written = ...)`, each comma-separated and sorted.
     */
    fun viewProperty(view: String, logic: Map<String, Access>) {
      val read = logic.filterValues { it.read }.keys.sorted().joinToString(",")
      val written = logic.filterValues { it.write }.keys.sorted()
      val annotation = "@LogicTypes(read = \"$read\", written = \"${written.joinToString(",")}\")"
      if (annotation.length + indent * 2 <= 100) {
        line(annotation)
      } else {
        line("@LogicTypes(")
        indent += 2
        // As ktfmt breaks an argument too long for its line: the string on a line of its own.
        for ((name, value) in listOf("read" to read, "written" to written.joinToString(","))) {
          if ("$name = \"$value\",".length + indent * 2 <= 100) {
            line("$name = \"$value\",")
          } else {
            line("$name =")
            indent += 2
            line("\"$value\",")
            indent -= 2
          }
        }
        indent -= 2
        line(")")
      }
      line("val $view: ${ViewsGenerator.viewType(view, written)}")
      line("  get() = intrinsic()")
    }

    fun property(
        name: String,
        type: String,
        access: Access,
        override: Boolean = false,
        writeOnlyMessage: String = "WRITE_ONLY",
    ) {
      val modifier = if (override) "override " else ""
      when {
        access.read && access.write -> {
          line("${modifier}var $name: $type")
          indent += 1
          line("get() = intrinsic()")
          line("set(value) = intrinsic()")
          indent -= 1
        }
        access.read -> {
          line("${modifier}val $name: $type")
          indent += 1
          line("get() = intrinsic()")
          indent -= 1
        }
        else -> {
          line("${modifier}var $name: $type")
          indent += 1
          line("@Deprecated($writeOnlyMessage, level = DeprecationLevel.ERROR) get() = intrinsic()")
          line("set(value) = intrinsic()")
          indent -= 1
        }
      }
    }

    fun deviceClass(
        name: String,
        prefab: Prefab,
        supertypes: String,
        overrides: Set<String> = emptySet(),
    ) {
      line("/** A ${prefab.name}. */")
      line("@PrefabName(\"${prefab.name}\")")
      block("class $name internal constructor() : $supertypes") {
        for ((logicType, access) in logic(prefab)) {
          property(logicType, type(logicType), access, override = logicType in overrides)
          line()
        }
        val views = views(prefab)
        for ((view, logic) in views) {
          viewProperty(view, logic)
          line()
        }
        deviceSlots(
            prefab,
            logic(prefab).keys +
                views.keys +
                setOf("Text", "slots", "PrefabHash", "NameHash", "ReferenceId"),
        )
        if (prefab.name in textDisplays) {
          line("/** Text of one to six ASCII characters, shown in the `String` mode. */")
          property("Text", "String", Access(read = false, write = true))
          line()
        }
        line("/** The ${prefab.name} prefab. */")
        line("companion object : Prefab()")
      }
    }

    fun entryPoint(header: String, deviceType: String, prefab: Prefab) {
      // A prefab with slots has its own batch type, to give a batch of its devices `slots`.
      val batch = if (prefab.slots.isEmpty()) "DeviceBatch<$deviceType>" else "Batch"
      line("/** The ${prefab.name} devices on the chip's network. */")
      line("@PrefabName(\"${prefab.name}\")")
      block(header) {
        line("/** The device on [pin], as a ${prefab.name}. */")
        line("fun at(pin: Device): $deviceType = intrinsic()")
        line()
        line("/** Every one on the network. */")
        line("val all: $batch")
        line("  get() = intrinsic()")
        line()
        line("/** Every one on the network named [name], which must be a constant. */")
        line("fun named(name: String): $batch = intrinsic()")
        if (prefab.slots.isNotEmpty()) {
          line()
          block("class Batch internal constructor() : DeviceBatch<$deviceType>()") {
            line("/** A slot of every one in the batch, by number. */")
            line("val slots: Slots<SlotBatch<${slotClassOf(prefab, slotsKind(prefab))}>>")
            line("  get() = intrinsic()")
          }
        }
      }
    }

    /** The logic types all of [members] can read, writable where all of them can write it. */
    fun common(members: List<Prefab>): Map<String, Access> {
      val logic = members.map { logic(it) }
      return logic
          .first()
          .keys
          .filter { key -> logic.all { it[key]?.read == true } }
          .associateWith { key ->
            Access(read = true, write = logic.all { it.getValue(key).write })
          }
    }

    /**
     * A family's interface, its members nested in it, and its entry point. A logic type it
     * [inherited] from the families it [extends] is declared there, and again here only where it is
     * a `var` here and a `val` there.
     */
    fun family(
        name: String,
        plural: String,
        members: Map<String, Prefab>,
        extends: List<String> = emptyList(),
        inherited: Map<String, Access> = emptyMap(),
    ) {
      val common = common(members.values.toList())
      line()
      line("/** Devices of one kind that share these logic types, each a nested class. */")
      val supertypes = if (extends.isEmpty()) "" else " : ${extends.joinToString(", ")}"
      block("interface $name$supertypes") {
        for ((logicType, access) in common) {
          val parent = inherited[logicType]
          if (parent != null && parent.write == access.write) continue
          val modifier = if (parent != null) "override " else ""
          line(
              if (access.write) "${modifier}var $logicType: ${type(logicType)}"
              else "val $logicType: ${type(logicType)}"
          )
          line()
        }
        for ((member, prefab) in members) {
          deviceClass(member, prefab, "TypedDevice(), $name", overrides = common.keys)
          line()
        }
        trimBlankLine()
      }
      line()
      line("/** The $name devices on the chip's network, by prefab. */")
      block("object $plural") {
        for ((member, prefab) in members) {
          entryPoint("object $member", "$name.$member", prefab)
          line()
        }
        trimBlankLine()
      }
    }

    fun slotType(logicType: String) =
        if (logicType in typing.booleanSlotLogicTypes) "Boolean" else "Double"

    /** The slot logic types a kind of slot can read, and those the game lets a program write. */
    fun slotReads(kind: String) =
        (slotKinds.getValue(kind) + typing.slotReadsAlways).distinct().sorted()

    fun slotWrites(kind: String) = typing.slotWrites[kind].orEmpty().toSet()

    /** A kind of slot: its logic types, read with `ls` and written with `ss`. */
    fun slotKind(kind: String) {
      val reads = slotReads(kind)
      val writes = slotWrites(kind)
      line()
      line("/** A $kind slot. */")
      block("class ${slotClass(kind)} internal constructor() : DeviceSlot()") {
        for (logicType in (reads + writes).distinct().sorted()) {
          property(logicType, slotType(logicType), Access(logicType in reads, logicType in writes))
          line()
        }
        trimBlankLine()
      }
    }

    /**
     * A kind of slot on a thing: the logic types the game lets a program read on any thing's slot,
     * and those this kind adds, and no writes, which the game has none of for things.
     */
    fun thingSlotKind(kind: String) {
      val reads =
          (typing.thingSlotReadsAlways + typing.thingSlotReadsByKind[kind].orEmpty())
              .distinct()
              .sorted()
      line()
      line("/** A $kind slot of a thing that isn't a structure, such as an item or a robot. */")
      block("class ${thingSlotClass(kind)} internal constructor() : DeviceSlot()") {
        for (logicType in reads) {
          property(logicType, slotType(logicType), Access(read = true, write = false))
          line()
        }
        trimBlankLine()
      }
    }

    /** The class of a [prefab]'s slot of [kind]: a thing's, or a structure's. */
    fun slotClassOf(prefab: Prefab, kind: String) =
        if (prefab.name in things) thingSlotClass(kind) else slotClass(kind)

    /** The kind all of a prefab's slots share, else `Common`, whose logic every slot can read. */
    fun slotsKind(prefab: Prefab) =
        prefab.slots.values.map { it.kind }.distinct().singleOrNull() ?: "Common"

    /** A device's `slots`, and its slots by the game's names for them. */
    fun deviceSlots(prefab: Prefab, taken: Set<String>) {
      if (prefab.slots.isEmpty()) return
      line("/** The device's slots, by number. */")
      line("val slots: Slots<${slotClassOf(prefab, slotsKind(prefab))}>")
      line("  get() = intrinsic()")
      line()
      val names = prefab.slots.values.mapNotNull { it.name }.groupingBy { it }.eachCount()
      for ((number, slot) in prefab.slots) {
        val name = slot.name ?: continue
        // A name that isn't an identifier, is given twice, or clashes with a property is left out.
        if (!IDENTIFIER.matches(name) || names.getValue(name) > 1 || name in taken) continue
        line("/** Slot $number. */")
        line("@SlotNumber($number)")
        line("val $name: ${slotClassOf(prefab, slot.kind)}")
        line("  get() = intrinsic()")
        line()
      }
    }

    fun trimBlankLine() {
      if (text.endsWith("\n\n")) text.setLength(text.length - 1)
    }

    override fun toString() = text.toString()
  }
}
